    private BinliSmsStatusUtil() {
    }

    /**
     * 是否成功状态
     */
    public static boolean isSuccess(String status) {
        return "DELIVRD".equals(status) || "0".equals(status) || "成功".equals(status);
    }

    /**
     * 状态代码 → 中文描述；未收录代码返回「发送失败(代码)」
     */
    public static String resolveDesc(String status) {
        if (StrUtil.isBlank(status)) {
            return "";
        }
        if (isSuccess(status)) {
            return "发送成功";
        }
        String desc = MAP.get(status);
        if (desc != null) {
            return desc;
        }
        // R:0213-R:0299 统一为「账号存在敏感信息」
        if (status.startsWith("R:")) {
            try {
                int n = Integer.parseInt(status.substring(2));
                if (n >= 213 && n <= 299) {
                    return "账号存在敏感信息";
                }
            } catch (NumberFormatException ignore) {
                // 非数字后缀，走兜底
            }
            return "发送失败(" + status + ")";
        }
        // XA: 运营商签名审核类错误（实测 XA:0003 = 签名未报备/未通过审核）
        if ("XA:0003".equals(status)) {
            return "签名未报备或未通过审核";
        }
        if (status.startsWith("XA:")) {
            return "签名相关失败(" + status + ")";
        }
        // LU: 联通网关错误（实测 LU:0003 平台显示 API失败）
        if ("LU:0003".equals(status)) {
            return "网关API拒绝";
        }
        if (status.startsWith("LU:")) {
            return "联通网关失败(" + status + ")";
        }
        // SGIP:xxx 运营商网关异常
        if (status.startsWith("SGIP:")) {
            return "运营商网关异常(" + status + ")";
        }
        // 负数码兜底
        if (status.startsWith("-")) {
            return "发送失败(" + status + ")";
        }
        return "发送失败(" + status + ")";
    }
